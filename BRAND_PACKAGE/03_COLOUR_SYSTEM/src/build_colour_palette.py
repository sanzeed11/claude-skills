def swatch(key, tall=False):
    c = C[key]
    ink = ink_for(c["hex"])
    p = c["pantone_nearest"][0]
    pant = f'{p["pantone"]} <span style="color:var(--fg-3)">ΔE {p["deltaE"]} · {p["reliability"]}</span>'
    cm = c["cmyk"]
    return f"""<div class="sw{' tall' if tall else ''}"><div class="col" style="background:{c['hex']};color:{ink}"><span class="hx">{c['hex']}</span></div>
<div class="b"><div class="n">{c['name']}</div><div class="r">{c['role']}</div>
<div class="v"><b>RGB</b>{c['rgb'][0]} {c['rgb'][1]} {c['rgb'][2]}<br><b>CMYK</b>{cm[0]} {cm[1]} {cm[2]} {cm[3]}<br><b>PMS</b>{pant}</div>
<div class="u">{c['usage']}</div></div></div>"""

def grid(keys, cols=4, tall=False):
    return f'<div class="sw-grid" style="grid-template-columns:repeat({cols},1fr)">' + "".join(swatch(k, tall) for k in keys) + "</div>"

