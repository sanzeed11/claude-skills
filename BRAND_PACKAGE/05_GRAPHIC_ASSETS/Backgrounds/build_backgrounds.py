#!/usr/bin/env python3
"""
build_backgrounds.py — renders every background from the sources in src/ (HTML via the kit's render.js,
A4 covers via the SVG masters) and writes the A4 cover SVG masters themselves.

  python3 build_backgrounds.py            # everything
  python3 build_backgrounds.py plates     # only the group whose name contains 'plates' (lamp, dusk, plaster, grain, presentation, covers, plates)

Outputs (all in this folder, named sanzeed-<deliverable>--<variant>-<size>.<ext>):
  lamp / dusk / plaster fills   JPG q90 at 1920x1080, 2560x1440, 1080x1920, 1080x1080
  grain variants                JPG q90 at 1920x1080 (charcoal, dusk, lamp — on pure black soft-light grain is invisible by definition)
  presentation backgrounds      PNG 1920x1080 (1x) + JPG q90 3840x2160 (2x) for title / content / section / end, dark and light
  A4 document covers            SVG master (210 x 297 mm) + PDF (Inkscape, vector) + PNG 2480x3508 (300 dpi)
  photo plates                  JPG q90 1920x1080 — approved project images under the veil with their wall label
"""
import sys, re, subprocess
from pathlib import Path
HERE = Path(__file__).resolve().parent; SRC = HERE / 'src'
sys.path.insert(0, str(HERE.parent / '_build')); import szlib as sz
f = sz.f
SIZES = [(1920, 1080), (2560, 1440), (1080, 1920), (1080, 1080)]

def jpg_from(html, out_jpg, w, h, scale=1, q=90):
    tmp = HERE / '_tmp.png'
    sz.render_html(html, tmp, w, h, scale=scale)
    sz.png_to_jpg(tmp, out_jpg, quality=q); tmp.unlink()

def covers():
    """A4 portrait covers: horizontal-descriptor lockup bottom-left at 20 mm margins (the rule for document
    covers), the doorway arch as a window motif, the lamp glow behind (dark) / plaster gradient (light),
    a beam with the point above the lockup. 1 user unit = 0.1 mm."""
    W, H = 2100, 2970; m = 200                       # 20 mm margins
    for ink in ('dark', 'light'):
        c = sz.INK[ink]
        logo, lw, lh = sz.logo_group('horizontal-descriptor', f'full-colour-{ink}', m, 0, 700)   # 70 mm wide (min 50 mm)
        ly = H - m - lh; logo = logo.replace('translate(200 0)', f'translate({m} {f(ly)})')
        x_clear = lh * 0.5                              # clear space = half the lockup's wordmark cap height... use half lockup height (generous)
        if ink == 'dark':
            bg = (f'<rect width="{W}" height="{H}" fill="#000000"/>'
                  f'<defs><radialGradient id="lamp" cx="{W*0.5}" cy="{H*0.42}" r="{W*0.62}" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#E9B25A" stop-opacity="0.55"/><stop offset="0.28" stop-color="#E9B25A" stop-opacity="0.12"/><stop offset="0.7" stop-color="#E9B25A" stop-opacity="0"/></radialGradient></defs>'
                  f'<rect id="lamp-glow" width="{W}" height="{H}" fill="url(#lamp)"/>')
        else:
            bg = (f'<defs><linearGradient id="plaster" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#FBF8F2"/><stop offset="1" stop-color="#ECE7DC"/></linearGradient></defs>'
                  f'<rect width="{W}" height="{H}" fill="url(#plaster)"/>')
        aw, ah = 1100, 1700                             # the arch window, upper right, bleeding off the top edge
        ax = W - m - aw
        op = 0.16 if ink == 'dark' else 0.14
        arch = (f'<defs><linearGradient id="arch-fade" x1="0" y1="{m}" x2="0" y2="{m + ah}" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{c["line"]}" stop-opacity="{op}"/><stop offset="0.55" stop-color="{c["line"]}" stop-opacity="{op}"/><stop offset="1" stop-color="{c["line"]}" stop-opacity="0"/></linearGradient></defs>'
                f'<path id="arch-window" d="M{ax} {m + ah} V{m + aw/2} A{aw/2} {aw/2} 0 0 1 {ax+aw} {m + aw/2} V{m + ah}" '
                f'fill="none" stroke="url(#arch-fade)" stroke-width="3"/>')
        beam_y = ly - x_clear - 40
        beam = (f'<g id="beam"><line x1="{m}" y1="{f(beam_y)}" x2="{W-m}" y2="{f(beam_y)}" stroke="{c["line"]}" stroke-opacity="{c["line_op"]}" stroke-width="3"/>'
                f'<circle cx="{m}" cy="{f(beam_y)}" r="14" fill="{c["gold"]}"/></g>')
        body = bg + arch + beam + logo
        title = f'Sanzeed — A4 document cover background ({ink})'
        desc = ('A4 portrait, 1 unit = 0.1 mm, 20 mm margins. Horizontal-descriptor lockup bottom-left (70 mm wide, min 50 mm), '
                'clear space kept above it; the doorway arch as a window motif; a beam with the point above the lockup. '
                f'{"Lamp glow on Gallery Black; use full-colour-dark logos and Gallery White type on it." if ink=="dark" else "Plaster gradient; use full-colour-light logos and Soot type on it."} '
                'The title sits at the top-left margin in Fraunces 300. Generated by Backgrounds/build_backgrounds.py.')
        svg = sz.svg(W, H, body, title, desc).replace(f'width="{W}" height="{H}"', 'width="210mm" height="297mm"', 1)
        svgp = sz.write(HERE / f'sanzeed-cover-a4--{ink}.svg', svg)
        subprocess.run(['inkscape', str(svgp), '--export-type=pdf', f'--export-filename={HERE / f"sanzeed-cover-a4--{ink}.pdf"}'], capture_output=True)
        # PNG at 300 dpi (2480 x 3508) through Chromium so gradients match the screen exactly
        wrap = SRC / f'sanzeed-cover-a4--{ink}.html'
        wrap.write_text(f'<!doctype html><html><head><meta charset="utf-8"><title>{title}</title><style>html,body{{margin:0;background:transparent}}img{{display:block;width:2480px;height:3508px}}</style></head><body><img src="../sanzeed-cover-a4--{ink}.svg" alt=""></body></html>')
        sz.render_html(wrap, HERE / f'sanzeed-cover-a4--{ink}-2480x3508.png', 2480, 3508, scale=1)
        print('cover', ink)

def main(only=None):
    groups = {
      'lamp':    lambda: [jpg_from(SRC/'sanzeed-bg-lamp--dark.html', HERE/f'sanzeed-bg-lamp--dark-{w}x{h}.jpg', w, h) for w, h in SIZES],
      'dusk':    lambda: [jpg_from(SRC/'sanzeed-bg-dusk--dark.html', HERE/f'sanzeed-bg-dusk--dark-{w}x{h}.jpg', w, h) for w, h in SIZES],
      'plaster': lambda: [jpg_from(SRC/'sanzeed-bg-plaster--light.html', HERE/f'sanzeed-bg-plaster--light-{w}x{h}.jpg', w, h) for w, h in SIZES],
      'grain':   lambda: [jpg_from(SRC/f'sanzeed-bg-grain--{g}.html', HERE/f'sanzeed-bg-grain--{g}-1920x1080.jpg', 1920, 1080) for g in ('charcoal', 'dusk', 'lamp')],
      'presentation': lambda: [(sz.render_html(SRC/f'sanzeed-bg-presentation-{k}--{t}.html', HERE/f'sanzeed-bg-presentation-{k}--{t}-1920x1080.png', 1920, 1080, scale=1),
                                jpg_from(SRC/f'sanzeed-bg-presentation-{k}--{t}.html', HERE/f'sanzeed-bg-presentation-{k}--{t}-3840x2160.jpg', 1920, 1080, scale=2))
                               for k in ('title', 'content', 'section', 'end') for t in ('dark', 'light')],
      'covers':  covers,
      'plates':  lambda: [jpg_from(SRC/f'sanzeed-bg-photo-plate--{s}.html', HERE/f'sanzeed-bg-photo-plate--{s}-1920x1080.jpg', 1920, 1080) for s in ('prime-minister-museum', 'ram-katha-show', 'buddha-park')],
    }
    for name, fn in groups.items():
        if only and only not in name: continue
        fn(); print('done', name)

if __name__ == '__main__': main(sys.argv[1] if len(sys.argv) > 1 else None)
